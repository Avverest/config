-- Вертикальные линии по уровням вложенности (indent-blankline).
--
-- Рисует линию на каждом уровне отступа, а блок, внутри которого сейчас
-- курсор, подсвечивает отдельным цветом. Границы блока определяются через
-- treesitter, поэтому работают по синтаксису, а не по одним пробелам.

require("ibl").setup({
	indent = {
		char = "│",
		tab_char = "│",
	},
	scope = {
		enabled = true, -- линия текущего блока — цветом IblScope
		show_start = false, -- без подчёркивания первой и последней строки блока:
		show_end = false, -- в плотном коде это лишний шум
	},
	exclude = {
		-- к встроенному списку (help, man, checkhealth, gitcommit и прочее)
		-- добавляем то, что появилось из нашего конфига
		filetypes = { "netrw", "lazy", "mason", "snacks_dashboard" },
	},
})
